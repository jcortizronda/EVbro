"""Ficha del coche, Costes, repostajes, coste de carga, historial guardado y cabecera. Ver tools/e2e/README.md."""
import os
import sys
import tempfile
from playwright.sync_api import sync_playwright

BASE = os.environ.get("EVBRO_URL", "http://127.0.0.1:8099")
USER = os.environ.get("EVBRO_USER", "juan")
PASSWORD = os.environ.get("EVBRO_PASSWORD", "una-contraseña-larga-1")
OUT = sys.argv[1] if len(sys.argv) > 1 else tempfile.mkdtemp(prefix="evbro-e2e-")
fails = []


def ok(c, m):
    print(("  ✔ " if c else "  ✘ ") + m)
    if not c:
        fails.append(m)


with sync_playwright() as p:
    b = p.chromium.launch()
    for theme in ("dark", "light"):
        ctx = b.new_context(viewport={"width": 390, "height": 844}, is_mobile=True, has_touch=True, locale="es-ES")
        ctx.request.post(f"{BASE}/api/auth/login", headers={"Origin": BASE}, data={"username": USER, "password": PASSWORD})
        ctx.add_init_script(f"localStorage.setItem('evbro_theme','{theme}')")
        ctx.add_init_script("new MutationObserver(() => { const b = document.querySelector('#appDialog.open #appDialogOk'); if (b) b.click(); }).observe(document, { attributes: true, subtree: true, attributeFilter: ['class'] })")   # the app's own confirm dialog is accepted
        pg = ctx.new_page()
        errs = []
        pg.on("pageerror", lambda e: errs.append(str(e)))
        pg.on("dialog", lambda d: (errs.append("diálogo del navegador: " + d.message), d.dismiss()))
        pg.goto(BASE)
        pg.wait_for_load_state("networkidle")
        pg.wait_for_timeout(1200)
        tag = theme
        txt = lambda s: pg.text_content(s).strip()

        # cabecera: título y estado arriba a la izquierda, dentro del mismo cuadro
        box = pg.evaluate("""() => { const b = document.getElementById('overviewBanner').getBoundingClientRect();
          const t = document.getElementById('vehicleName').getBoundingClientRect();
          const s = document.getElementById('vehicleStatusBadge').getBoundingClientRect();
          const v = document.getElementById('vehicleVin').getBoundingClientRect();
          return {bt: b.top, bl: b.left, bb: b.bottom, br: b.right, tt: t.top, tl: t.left, st: s.top, sb: s.bottom, sr: s.right, vb: v.bottom,
                  pencil: !!document.querySelector('#overviewBanner [data-on-click*="openEditVehicleModal"]')}; }""")
        ok(box["tt"] - box["bt"] < 28 and box["tl"] - box["bl"] < 24, f"{tag}: el título está arriba a la izquierda ({box['tt'] - box['bt']:.0f}, {box['tl'] - box['bl']:.0f} px)")
        ok(box["st"] >= box["bt"] and box["sb"] <= box["bb"] and box["st"] - box["bt"] < 40, f"{tag}: el estado está en el mismo cuadro, arriba")
        ok(box["br"] - box["sr"] < 24, f"{tag}: el estado está arriba a la derecha ({box['br'] - box['sr']:.0f} px del borde)")
        ok(box["bb"] - box["vb"] < 20 and not box["pencil"], f"{tag}: VIN y matrícula abajo, sin botón de lápiz")
        pg.screenshot(path=f"{OUT}/profile-home-{theme}.png")

        # ficha del coche
        pg.evaluate("openVehicleSettings()")
        pg.wait_for_timeout(500)
        # secciones plegables: al principio solo Identidad abierta; se recuerda lo que se abre
        opened = pg.eval_on_selector_all(".vp-section[open]", "e=>e.map(d=>d.dataset.key)")
        ok(opened == ["identity"], f"{tag}: la ficha arranca con solo «Identidad» abierta ({opened})")
        ok(pg.is_hidden("#vpPurchasePrice"), f"{tag}: los campos de una sección plegada no se ven")
        pg.click(".vp-section[data-key='purchase'] > summary")
        pg.wait_for_timeout(200)
        ok(pg.is_visible("#vpPurchasePrice"), f"{tag}: al tocar el título se despliega")
        pg.reload()
        pg.wait_for_load_state("networkidle")
        pg.wait_for_timeout(1200)
        pg.evaluate("openVehicleSettings()")
        pg.wait_for_timeout(500)
        ok(pg.eval_on_selector_all(".vp-section[open]", "e=>e.map(d=>d.dataset.key)") == ["identity", "purchase"], f"{tag}: se recuerda lo que se desplegó")
        pg.click("button:text-is(\"Plegar todo\")")
        ok(pg.eval_on_selector_all(".vp-section[open]", "e=>e.length") == 0, f"{tag}: «Plegar todo» las cierra")
        pg.click("button:text-is(\"Desplegar todo\")")
        ok(pg.eval_on_selector_all(".vp-section[open]", "e=>e.length") == 6, f"{tag}: «Desplegar todo» las abre")
        models = pg.eval_on_selector_all("#vpModel option", "e=>e.map(o=>o.value)")
        ok(all(m in models for m in ("S700 PHEV", "S800 PHEV", "S900 PHEV")), f"{tag}: modelos en lista desplegable ({models})")
        ok(pg.input_value("#vpVin") != "" and pg.is_disabled("#vpVin") or pg.get_attribute("#vpVin", "readonly") is not None, f"{tag}: el bastidor se lee de la cuenta y no se edita")
        pg.fill("#vpPlate", "1234ABC")
        pg.fill("#vpYear", "2025")
        pg.fill("#vpPurchasePrice", "32000")
        pg.fill("#vpRegDate", "2025-03-20")
        pg.fill("#vpDeliveryDate", "2025-03-31")
        pg.fill("#vpInsurer", "Mapfre")
        pg.fill("#vpPolicy", "P-998877")
        pg.fill("#vpInsRenewal", "2026-12-01")
        pg.fill("#vpInsCoverage", "Todo riesgo")
        pg.fill("#vpTrim", "Luxury")
        pg.select_option("#vpEnvLabel", "ECO")
        pg.fill("#vpTyreFrontSize", "215/55 R18")
        pg.fill("#vpTyreRearSize", "215/55 R18")
        pg.fill("#vpTyreFrontBar", "2.4")
        pg.fill("#vpTyreRearBar", "2.5")
        # marca: lista con EBRO primero, «Otra…» al final; el modelo es la lista S700/S800/S900 solo para EBRO
        brands = pg.eval_on_selector_all("#vpBrand option", "e=>e.map(o=>o.value)")
        ok(brands[0] == "EBRO" and brands[-1] == "__other" and "Toyota" in brands and "Škoda" in brands, f"{tag}: marcas en lista con EBRO primero ({brands[:3]}…)")
        ok(pg.input_value("#vpBrand") == "EBRO" and pg.is_visible("#vpModel") and pg.is_hidden("#vpModelText"), f"{tag}: con EBRO el modelo es la lista")
        pg.select_option("#vpBrand", "Toyota")
        ok(pg.is_hidden("#vpModel") and pg.is_visible("#vpModelText"), f"{tag}: con otra marca el modelo es texto libre")
        pg.select_option("#vpBrand", "__other")
        ok(pg.is_visible("#vpBrandOther"), f"{tag}: «Otra…» muestra el campo de texto")
        pg.select_option("#vpBrand", "EBRO")
        ok(pg.is_hidden("#vpBrandOther") and pg.is_visible("#vpModel"), f"{tag}: volver a EBRO recupera la lista de modelos")
        # la entrega puede ser posterior o anterior a la matriculación (coche de segunda mano): sin límite en el selector
        ok(not pg.get_attribute("#vpDeliveryDate", "min"), f"{tag}: el selector de entrega no tiene mínimo")
        ok("anterior a la matriculación" not in txt(".vp-section[data-key='purchase']"), f"{tag}: sin la regla de la entrega en la ayuda")
        pg.fill("#vpRegDate", "2021-03-20")
        ok(pg.locator("#vpDefaultPrice").count() == 0 and pg.locator("#vpPurchaseDate").count() == 0 and pg.locator("#vpTyreTol").count() == 0,
           f"{tag}: la ficha ya no tiene fecha de compra, precio por defecto ni margen de presión")
        ok(pg.locator(".vp-section").count() == 6, f"{tag}: seis secciones separadas ({pg.locator('.vp-section').count()})")
        pg.screenshot(path=f"{OUT}/profile-form-{theme}.png", full_page=True)
        pg.click("#vpSave")
        pg.wait_for_timeout(900)
        v = pg.evaluate("fetch('/api/vehicles').then(r=>r.json()).then(a=>a[0])")
        ok(v["license_plate"] == "1234ABC" and v["purchase_price"] == 32000 and v["insurance_company"] == "Mapfre", f"{tag}: la ficha se guarda en el servidor")
        ok(v["tyre_front_pressure_bar"] == 2.4 and v["delivery_date"].startswith("2025-03-31") and v["registration_date"].startswith("2021-03-20"),
           f"{tag}: presiones y entrega (posterior a la matriculación) guardadas")
        ok(v["insurance_renewal_date"].startswith("2026-12-01") and v["env_label"] == "ECO" and v["trim"] == "Luxury", f"{tag}: renovación del seguro, versión y etiqueta guardadas")
        ok("1234ABC" in txt("#heroPlateBadge"), f"{tag}: la matrícula se refleja en la cabecera")
        over = pg.evaluate("document.documentElement.scrollWidth - document.documentElement.clientWidth")
        ok(over <= 0, f"{tag}: ficha sin desbordamiento horizontal ({over} px)")

        # Gastos: un gasto con próxima fecha y un repostaje a mano
        pg.evaluate("switchTab('expenses')")
        pg.wait_for_timeout(900)
        ok(pg.is_hidden("#exDueCard") or pg.locator("#exDueList .ex-due-row").count() <= 1, f"{tag}: sin gastos con fecha solo aparece, como mucho, la renovación del seguro")
        pg.click("text=Añadir gasto")
        pg.wait_for_timeout(300)
        ok(pg.is_visible("#expenseModal"), f"{tag}: se abre el formulario de gasto")
        pg.select_option("#exCategory", "tax")
        pg.fill("#exName", "Impuesto de circulación 2026")
        pg.fill("#exAmount", "85.5")
        pg.fill("#exDate", "2026-03-01")
        pg.fill("#exDue", "2027-03-01")
        pg.click("#expenseModal >> text=Guardar")
        pg.wait_for_timeout(900)
        ok("Impuesto de circulación 2026" in txt("#exList") and "85,50" in txt("#exTotal"), f"{tag}: el gasto aparece y suma ({txt('#exTotal')})")
        ok(pg.is_visible("#exDueCard") and "Impuesto" in txt("#exDueList"), f"{tag}: aparece en próximos vencimientos")
        pg.click("#exChips >> text=Seguro")
        pg.wait_for_timeout(200)
        ok("85,50" not in txt("#exTotal") and "0,00" in txt("#exTotal"), f"{tag}: el filtro por categoría funciona")
        pg.click("#exChips >> text=Todas")
        pg.screenshot(path=f"{OUT}/expenses-{theme}.png", full_page=True)
        over = pg.evaluate("document.documentElement.scrollWidth - document.documentElement.clientWidth")
        ok(over <= 0, f"{tag}: gastos sin desbordamiento horizontal ({over} px)")

        # Repostajes: sección propia con consumo real
        pg.evaluate("switchTab('refuels')")
        pg.wait_for_timeout(900)
        pg.click("#rfListCard >> text=Añadir repostaje")
        pg.wait_for_timeout(300)
        ok(pg.is_visible("#refuelModal"), f"{tag}: se abre el formulario de repostaje")
        pg.fill("#rfLiters", "30")
        pg.fill("#rfPrice", "1.65")
        pg.fill("#rfStation", "Repsol")
        pg.click("#refuelModal >> text=Guardar")
        pg.wait_for_timeout(900)
        ok("Repsol" in txt("#rfList") and "lleno" in txt("#rfList"), f"{tag}: el repostaje aparece en la lista, marcado como lleno")
        ok("49,50" in txt("#rfTotalCost") and "1,650" in txt("#rfPriceLiter"), f"{tag}: total y precio medio del litro ({txt('#rfTotalCost')} · {txt('#rfPriceLiter')})")
        pg.click("#rfList .costs-row-btn >> nth=0")
        pg.wait_for_timeout(300)
        ok(pg.input_value("#rfLiters") == "30" and pg.is_checked("#rfFull"), f"{tag}: al tocarlo se abre para editar")
        pg.click("#refuelModal >> text=Cancelar")
        pg.screenshot(path=f"{OUT}/refuels-{theme}.png", full_page=True)
        over = pg.evaluate("document.documentElement.scrollWidth - document.documentElement.clientWidth")
        ok(over <= 0, f"{tag}: repostajes sin desbordamiento horizontal ({over} px)")

        # Costes: balance de solo lectura
        pg.evaluate("switchTab('costs')")
        pg.wait_for_timeout(900)
        ok("32" in txt("#costsPurchase").replace(".", ""), f"{tag}: la compra suma al total ({txt('#costsPurchase')})")
        ok("49,50" in txt("#costsRefuels"), f"{tag}: 30 L x 1,65 = 49,50 € ({txt('#costsRefuels')})")
        ok("85,50" in txt("#costsExpenses") and "Impuestos" in txt("#costsByCat"), f"{tag}: los gastos suman y se desglosan por categoría")
        ok(pg.locator("#tabCosts button:has-text('Añadir')").count() == 0, f"{tag}: Costes es solo estadística (no tiene botones de añadir)")
        pg.click("#tabCosts [data-period='12m']")
        pg.wait_for_timeout(700)
        ok("12 meses" in txt("#costsHeroLabel"), f"{tag}: el selector de periodo funciona")
        pg.click("#tabCosts [data-period='all']")
        pg.wait_for_timeout(500)
        pg.screenshot(path=f"{OUT}/costs-{theme}.png", full_page=True)
        over = pg.evaluate("document.documentElement.scrollWidth - document.documentElement.clientWidth")
        ok(over <= 0, f"{tag}: costes sin desbordamiento horizontal ({over} px)")
        # borrar lo creado
        pg.evaluate("switchTab('refuels')")
        pg.wait_for_timeout(700)
        pg.click("#rfList .costs-row-btn >> nth=0")
        pg.wait_for_timeout(300)
        pg.click("#rfDelete")
        pg.wait_for_timeout(800)
        ok("Repsol" not in txt("#rfList"), f"{tag}: el repostaje se borra")
        pg.evaluate("switchTab('expenses')")
        pg.wait_for_timeout(700)
        pg.click("#exList .costs-row-btn >> nth=0")
        pg.wait_for_timeout(300)
        pg.click("#exDelete")
        pg.wait_for_timeout(800)
        ok("Impuesto de circulación" not in txt("#exList"), f"{tag}: el gasto se borra")

        # (el historial guardado ya no está en la app: es un ajuste del servidor y vive en la consola; ver tools/e2e/admin.py)
        # aviso de presión de neumáticos
        pg.evaluate("switchTab('settings'); switchSettingsSubTab('notifs')")
        pg.wait_for_timeout(700)
        ok(pg.locator("#notifEvtTyres").count() == 1 and pg.locator("#notifTyreTol").count() == 1 and pg.locator("#notifEvtRenewals").count() == 1, f"{tag}: presión (con su margen) y vencimientos están en Avisos")
        pg.fill("#notifTyreTol", "15")
        pg.click("text=Guardar Ajustes de Notificaciones")
        pg.wait_for_timeout(900)
        ok((pg.evaluate("fetch('/api/vehicles').then(r=>r.json()).then(a=>a[0])"))["tyre_pressure_tolerance_pct"] == 15, f"{tag}: el margen se guarda en el coche")

        # coche sin cuenta Ebro: su `vin` es interno; el campo del bastidor edita el número de bastidor (informativo)
        demo_vin = pg.evaluate("currentVin")
        man = pg.evaluate("""fetch('/api/vehicles', {method: 'POST', headers: {'Content-Type': 'application/json'},
          body: JSON.stringify({name: 'Corolla de prueba', model: 'S900 PHEV'})}).then(r => r.json())""")
        pg.evaluate(f"loadVehicles().then(() => selectVehicle('{man['vin']}'))")
        pg.wait_for_timeout(900)
        pg.evaluate("openVehicleSettings()")
        pg.wait_for_timeout(500)
        ok(pg.get_attribute("#vpVin", "readonly") is None and pg.input_value("#vpVin") == "", f"{tag}: en un coche sin cuenta el bastidor se edita y empieza vacío")
        ok("informativo" in txt("#vpVinHint"), f"{tag}: la ayuda dice que es solo informativo ({txt('#vpVinHint')})")
        pg.fill("#vpVin", "jtdkb20u093123")
        pg.select_option("#vpBrand", "Toyota")
        pg.fill("#vpModelText", "Corolla")
        pg.click("#vpSave")
        pg.wait_for_timeout(900)
        m = pg.evaluate(f"fetch('/api/vehicles').then(r=>r.json()).then(a=>a.find(x=>x.vin==='{man['vin']}'))")
        ok(m["chassis_number"] == "JTDKB20U093123" and m["vin"] == man["vin"], f"{tag}: el bastidor se guarda en mayúsculas sin tocar el identificador ({m['chassis_number']})")
        ok(m["brand"] == "Toyota" and m["model"] == "Corolla", f"{tag}: marca y modelo libre guardados ({m['brand']} {m['model']})")
        ok(pg.input_value("#vpBrand") == "Toyota" and pg.input_value("#vpModelText") == "Corolla", f"{tag}: la ficha recarga marca y modelo")
        pg.fill("#vpVin", "CORTO")
        pg.click("#vpSave")
        pg.wait_for_timeout(600)
        m = pg.evaluate(f"fetch('/api/vehicles').then(r=>r.json()).then(a=>a.find(x=>x.vin==='{man['vin']}'))")
        ok(m["chassis_number"] == "JTDKB20U093123", f"{tag}: un bastidor demasiado corto no se guarda")
        pg.screenshot(path=f"{OUT}/profile-manual-{theme}.png", full_page=True)
        # con otra marca no hay plan oficial: ni interruptor ni vista oficial; la ITV sigue
        pg.evaluate("switchTab('maintenance')")
        pg.wait_for_timeout(900)
        ok(pg.is_hidden("#maintModeSwitch") and pg.is_hidden("#maintOfficialView") and pg.is_visible("#maintCustomView"), f"{tag}: otra marca solo tiene el plan personalizado")
        ok(pg.is_visible("#maintItvCard"), f"{tag}: la ITV se ve con cualquier marca")
        pg.screenshot(path=f"{OUT}/maintenance-other-brand-{theme}.png", full_page=True)
        pg.evaluate(f"fetch('/api/vehicles/{man['vin']}', {{method: 'DELETE'}}).then(() => loadVehicles()).then(() => selectVehicle('{demo_vin}'))")
        pg.wait_for_timeout(900)
        # Ebro: el estado de la cuenta oficial solo cuenta los coches de la cuenta (no los añadidos a mano)
        st = pg.evaluate("fetch('/api/account/status').then(r=>r.json())")
        ok(all(not x["vin"].startswith("MAN") for x in st["vehicles"]), f"{tag}: la cuenta Ebro no lista coches sin cuenta")

        # Sistema: la versión
        pg.evaluate("switchTab('settings'); switchSettingsSubTab('system')")
        pg.wait_for_timeout(700)
        ok(txt("#appVersion").startswith("EVBro ") and len(txt("#appVersion")) > 9, f"{tag}: Sistema muestra la versión ({txt('#appVersion')})")
        ok("Información del Servidor" not in pg.text_content("#settingsSubTabSystem"), f"{tag}: ya no está la tarjeta de información del servidor")
        pg.screenshot(path=f"{OUT}/system-{theme}.png", full_page=True)

        ok(not errs, f"{tag}: sin errores JS {errs[:2]}")
        ctx.close()
        if theme == "dark":
            import subprocess
            subprocess.run([os.path.join(os.path.dirname(__file__), "demo_server.sh"), "start"], check=True, capture_output=True)
    b.close()
print("FALLOS:", fails if fails else "ninguno")
sys.exit(1 if fails else 0)
