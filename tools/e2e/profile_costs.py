"""Car sheet, Costes, refuels, charge cost, saved history and header. See tools/e2e/README.md."""
import os
import sys
import tempfile
from playwright.sync_api import sync_playwright

BASE = os.environ.get("EVBRO_URL", "http://127.0.0.1:8099")
USER = os.environ.get("EVBRO_USER", "juan")
PASSWORD = os.environ.get("EVBRO_PASSWORD", "una-contraseña-larga-1")
OUT = sys.argv[1] if len(sys.argv) > 1 else tempfile.mkdtemp(prefix="evbro-e2e-")
fails = []


def ok(c, m):
    print(("  ✔ " if c else "  ✘ ") + m)
    if not c:
        fails.append(m)


with sync_playwright() as p:
    b = p.chromium.launch()
    for theme in ("dark", "light"):
        ctx = b.new_context(viewport={"width": 390, "height": 844}, is_mobile=True, has_touch=True, locale="es-ES")
        ctx.request.post(f"{BASE}/api/auth/login", headers={"Origin": BASE}, data={"username": USER, "password": PASSWORD})
        ctx.add_init_script(f"localStorage.setItem('evbro_theme','{theme}')")
        ctx.add_init_script("new MutationObserver(() => { const b = document.querySelector('#appDialog.open #appDialogOk'); if (b) b.click(); }).observe(document, { attributes: true, subtree: true, attributeFilter: ['class'] })")   # the app's own confirm dialog is accepted
        pg = ctx.new_page()
        errs = []
        pg.on("pageerror", lambda e: errs.append(str(e)))
        pg.on("dialog", lambda d: (errs.append("browser dialog: " + d.message), d.dismiss()))
        pg.goto(BASE)
        pg.wait_for_load_state("networkidle")
        pg.wait_for_timeout(1200)
        tag = theme
        txt = lambda s: pg.text_content(s).strip()

        # header: title and status at the top left, inside the same box
        box = pg.evaluate("""() => { const b = document.getElementById('overviewBanner').getBoundingClientRect();
          const t = document.getElementById('vehicleName').getBoundingClientRect();
          const s = document.getElementById('vehicleStatusBadge').getBoundingClientRect();
          const v = document.getElementById('vehicleVin').getBoundingClientRect();
          return {bt: b.top, bl: b.left, bb: b.bottom, br: b.right, tt: t.top, tl: t.left, st: s.top, sb: s.bottom, sr: s.right, vb: v.bottom,
                  pencil: !!document.querySelector('#overviewBanner [data-on-click*="openEditVehicleModal"]')}; }""")
        ok(box["tt"] - box["bt"] < 28 and box["tl"] - box["bl"] < 24, f"{tag}: the title is at the top left ({box['tt'] - box['bt']:.0f}, {box['tl'] - box['bl']:.0f} px)")
        ok(box["st"] >= box["bt"] and box["sb"] <= box["bb"] and box["st"] - box["bt"] < 40, f"{tag}: the status is in the same box, at the top")
        ok(box["br"] - box["sr"] < 24, f"{tag}: the status is at the top right ({box['br'] - box['sr']:.0f} px from the edge)")
        ok(box["bb"] - box["vb"] < 20 and not box["pencil"], f"{tag}: VIN and plate at the bottom, no pencil button")
        pg.screenshot(path=f"{OUT}/profile-home-{theme}.png")

        # car sheet
        pg.evaluate("openVehicleSettings()")
        pg.wait_for_timeout(500)
        # collapsible sections: at first only Identidad is open; what gets opened is remembered
        opened = pg.eval_on_selector_all(".vp-section[open]", "e=>e.map(d=>d.dataset.key)")
        ok(opened == ["identity"], f"{tag}: the sheet starts with only «Identidad» open ({opened})")
        ok(pg.is_hidden("#vpPurchasePrice"), f"{tag}: the fields of a collapsed section are not visible")
        pg.click(".vp-section[data-key='purchase'] > summary")
        pg.wait_for_timeout(200)
        ok(pg.is_visible("#vpPurchasePrice"), f"{tag}: tapping the title expands it")
        pg.reload()
        pg.wait_for_load_state("networkidle")
        pg.wait_for_timeout(1200)
        pg.evaluate("openVehicleSettings()")
        pg.wait_for_timeout(500)
        ok(pg.eval_on_selector_all(".vp-section[open]", "e=>e.map(d=>d.dataset.key)") == ["identity", "purchase"], f"{tag}: what was expanded is remembered")
        pg.click("button:text-is(\"Plegar todo\")")
        ok(pg.eval_on_selector_all(".vp-section[open]", "e=>e.length") == 0, f"{tag}: «Plegar todo» closes them")
        pg.click("button:text-is(\"Desplegar todo\")")
        ok(pg.eval_on_selector_all(".vp-section[open]", "e=>e.length") == 6, f"{tag}: «Desplegar todo» opens them")
        models = pg.eval_on_selector_all("#vpModel option", "e=>e.map(o=>o.value)")
        ok(all(m in models for m in ("S700 PHEV", "S800 PHEV", "S900 PHEV")), f"{tag}: models in a drop-down list ({models})")
        ok(pg.input_value("#vpVin") != "" and pg.is_disabled("#vpVin") or pg.get_attribute("#vpVin", "readonly") is not None, f"{tag}: the chassis number is read from the account and not editable")
        pg.fill("#vpPlate", "1234ABC")
        pg.fill("#vpYear", "2025")
        pg.fill("#vpPurchasePrice", "32000")
        pg.fill("#vpRegDate", "2025-03-20")
        pg.fill("#vpDeliveryDate", "2025-03-31")
        pg.fill("#vpInsurer", "Mapfre")
        pg.fill("#vpPolicy", "P-998877")
        pg.fill("#vpInsRenewal", "2026-12-01")
        pg.fill("#vpInsCoverage", "Todo riesgo")
        pg.fill("#vpTrim", "Luxury")
        pg.select_option("#vpEnvLabel", "ECO")
        pg.fill("#vpTyreFrontSize", "215/55 R18")
        pg.fill("#vpTyreRearSize", "215/55 R18")
        pg.fill("#vpTyreFrontBar", "2.4")
        pg.fill("#vpTyreRearBar", "2.5")
        # brand: list with EBRO first, «Otra…» last; the model is the S700/S800/S900 list only for EBRO
        brands = pg.eval_on_selector_all("#vpBrand option", "e=>e.map(o=>o.value)")
        ok(brands[0] == "EBRO" and brands[-1] == "__other" and "Toyota" in brands and "Škoda" in brands, f"{tag}: brands in a list with EBRO first ({brands[:3]}…)")
        ok(pg.input_value("#vpBrand") == "EBRO" and pg.is_visible("#vpModel") and pg.is_hidden("#vpModelText"), f"{tag}: with EBRO the model is the list")
        pg.select_option("#vpBrand", "Toyota")
        ok(pg.is_hidden("#vpModel") and pg.is_visible("#vpModelText"), f"{tag}: with another brand the model is free text")
        pg.select_option("#vpBrand", "__other")
        ok(pg.is_visible("#vpBrandOther"), f"{tag}: «Otra…» shows the text field")
        pg.select_option("#vpBrand", "EBRO")
        ok(pg.is_hidden("#vpBrandOther") and pg.is_visible("#vpModel"), f"{tag}: going back to EBRO restores the model list")
        # delivery can be after or before registration (second-hand car): no limit in the picker
        ok(not pg.get_attribute("#vpDeliveryDate", "min"), f"{tag}: the delivery picker has no minimum")
        ok("anterior a la matriculación" not in txt(".vp-section[data-key='purchase']"), f"{tag}: no delivery rule in the help text")
        pg.fill("#vpRegDate", "2021-03-20")
        ok(pg.locator("#vpDefaultPrice").count() == 0 and pg.locator("#vpPurchaseDate").count() == 0 and pg.locator("#vpTyreTol").count() == 0,
           f"{tag}: the sheet no longer has a purchase date, a default price or a pressure margin")
        ok(pg.locator(".vp-section").count() == 6, f"{tag}: six separate sections ({pg.locator('.vp-section').count()})")
        pg.screenshot(path=f"{OUT}/profile-form-{theme}.png", full_page=True)
        pg.click("#vpSave")
        pg.wait_for_timeout(900)
        v = pg.evaluate("fetch('/api/vehicles').then(r=>r.json()).then(a=>a[0])")
        ok(v["license_plate"] == "1234ABC" and v["purchase_price"] == 32000 and v["insurance_company"] == "Mapfre", f"{tag}: the sheet is saved on the server")
        ok(v["tyre_front_pressure_bar"] == 2.4 and v["delivery_date"].startswith("2025-03-31") and v["registration_date"].startswith("2021-03-20"),
           f"{tag}: pressures and delivery (after registration) saved")
        ok(v["insurance_renewal_date"].startswith("2026-12-01") and v["env_label"] == "ECO" and v["trim"] == "Luxury", f"{tag}: insurance renewal, version and label saved")
        ok("1234ABC" in txt("#heroPlateBadge"), f"{tag}: the plate shows in the header")
        over = pg.evaluate("document.documentElement.scrollWidth - document.documentElement.clientWidth")
        ok(over <= 0, f"{tag}: sheet without horizontal overflow ({over} px)")

        # Gastos: an expense with a next date and a manual refuel
        pg.evaluate("switchTab('expenses')")
        pg.wait_for_timeout(900)
        ok(pg.is_hidden("#exDueCard") or pg.locator("#exDueList .ex-due-row").count() <= 1, f"{tag}: without dated expenses at most the insurance renewal shows up")
        pg.click("text=Añadir gasto")
        pg.wait_for_timeout(300)
        ok(pg.is_visible("#expenseModal"), f"{tag}: the expense form opens")
        pg.select_option("#exCategory", "tax")
        pg.fill("#exName", "Impuesto de circulación 2026")
        pg.fill("#exAmount", "85.5")
        pg.fill("#exDate", "2026-03-01")
        pg.fill("#exDue", "2027-03-01")
        pg.click("#expenseModal >> text=Guardar")
        pg.wait_for_timeout(900)
        ok("Impuesto de circulación 2026" in txt("#exList") and "85,50" in txt("#exTotal"), f"{tag}: the expense shows up and adds up ({txt('#exTotal')})")
        ok(pg.is_visible("#exDueCard") and "Impuesto" in txt("#exDueList"), f"{tag}: it shows up in upcoming due dates")
        pg.click("#exChips >> text=Seguro")
        pg.wait_for_timeout(200)
        ok("85,50" not in txt("#exTotal") and "0,00" in txt("#exTotal"), f"{tag}: the category filter works")
        pg.click("#exChips >> text=Todas")
        pg.screenshot(path=f"{OUT}/expenses-{theme}.png", full_page=True)
        over = pg.evaluate("document.documentElement.scrollWidth - document.documentElement.clientWidth")
        ok(over <= 0, f"{tag}: expenses without horizontal overflow ({over} px)")

        # Repostajes: its own section with real consumption
        pg.evaluate("switchTab('refuels')")
        pg.wait_for_timeout(900)
        pg.click("#rfListCard >> text=Añadir repostaje")
        pg.wait_for_timeout(300)
        ok(pg.is_visible("#refuelModal"), f"{tag}: the refuel form opens")
        pg.fill("#rfLiters", "30")
        pg.fill("#rfPrice", "1.65")
        pg.fill("#rfStation", "Repsol")
        pg.click("#refuelModal >> text=Guardar")
        pg.wait_for_timeout(900)
        ok("Repsol" in txt("#rfList") and "lleno" in txt("#rfList"), f"{tag}: the refuel shows up in the list, marked as full")
        ok("49,50" in txt("#rfTotalCost") and "1,650" in txt("#rfPriceLiter"), f"{tag}: total and average price per litre ({txt('#rfTotalCost')} · {txt('#rfPriceLiter')})")
        pg.click("#rfList .costs-row-btn >> nth=0")
        pg.wait_for_timeout(300)
        ok(pg.input_value("#rfLiters") == "30" and pg.is_checked("#rfFull"), f"{tag}: tapping it opens it for editing")
        pg.click("#refuelModal >> text=Cancelar")
        pg.screenshot(path=f"{OUT}/refuels-{theme}.png", full_page=True)
        over = pg.evaluate("document.documentElement.scrollWidth - document.documentElement.clientWidth")
        ok(over <= 0, f"{tag}: refuels without horizontal overflow ({over} px)")

        # Costes: read-only balance
        pg.evaluate("switchTab('costs')")
        pg.wait_for_timeout(900)
        ok("32" in txt("#costsPurchase").replace(".", ""), f"{tag}: the purchase adds to the total ({txt('#costsPurchase')})")
        ok("49,50" in txt("#costsRefuels"), f"{tag}: 30 L x 1,65 = 49,50 € ({txt('#costsRefuels')})")
        ok("85,50" in txt("#costsExpenses") and "Impuestos" in txt("#costsByCat"), f"{tag}: the expenses add up and are broken down by category")
        ok(pg.locator("#tabCosts button:has-text('Añadir')").count() == 0, f"{tag}: Costes is statistics only (no add buttons)")
        pg.click("#tabCosts [data-period='12m']")
        pg.wait_for_timeout(700)
        ok("12 meses" in txt("#costsHeroLabel"), f"{tag}: the period picker works")
        pg.click("#tabCosts [data-period='all']")
        pg.wait_for_timeout(500)
        pg.screenshot(path=f"{OUT}/costs-{theme}.png", full_page=True)
        over = pg.evaluate("document.documentElement.scrollWidth - document.documentElement.clientWidth")
        ok(over <= 0, f"{tag}: costs without horizontal overflow ({over} px)")
        # delete what was created
        pg.evaluate("switchTab('refuels')")
        pg.wait_for_timeout(700)
        pg.click("#rfList .costs-row-btn >> nth=0")
        pg.wait_for_timeout(300)
        pg.click("#rfDelete")
        pg.wait_for_timeout(800)
        ok("Repsol" not in txt("#rfList"), f"{tag}: the refuel is deleted")
        pg.evaluate("switchTab('expenses')")
        pg.wait_for_timeout(700)
        pg.click("#exList .costs-row-btn >> nth=0")
        pg.wait_for_timeout(300)
        pg.click("#exDelete")
        pg.wait_for_timeout(800)
        ok("Impuesto de circulación" not in txt("#exList"), f"{tag}: the expense is deleted")

        # (the saved history is no longer in the app: it is a server setting and lives in the console; see tools/e2e/admin.py)
        # tyre pressure alert
        pg.evaluate("switchTab('settings'); switchSettingsSubTab('notifs')")
        pg.wait_for_timeout(700)
        ok(pg.locator("#notifEvtTyres").count() == 1 and pg.locator("#notifTyreTol").count() == 1 and pg.locator("#notifEvtRenewals").count() == 1, f"{tag}: pressure (with its margin) and due dates are in Avisos")
        pg.fill("#notifTyreTol", "15")
        pg.click("text=Guardar Ajustes de Notificaciones")
        pg.wait_for_timeout(900)
        ok((pg.evaluate("fetch('/api/vehicles').then(r=>r.json()).then(a=>a[0])"))["tyre_pressure_tolerance_pct"] == 15, f"{tag}: the margin is saved on the car")

        # car without an Ebro account: its `vin` is internal; the chassis field edits the chassis number (informative)
        demo_vin = pg.evaluate("currentVin")
        man = pg.evaluate("""fetch('/api/vehicles', {method: 'POST', headers: {'Content-Type': 'application/json'},
          body: JSON.stringify({name: 'Corolla de prueba', model: 'S900 PHEV'})}).then(r => r.json())""")
        pg.evaluate(f"loadVehicles().then(() => selectVehicle('{man['vin']}'))")
        pg.wait_for_timeout(900)
        pg.evaluate("openVehicleSettings()")
        pg.wait_for_timeout(500)
        ok(pg.get_attribute("#vpVin", "readonly") is None and pg.input_value("#vpVin") == "", f"{tag}: on a car without an account the chassis number is editable and starts empty")
        ok("informativo" in txt("#vpVinHint"), f"{tag}: the help says it is only informative ({txt('#vpVinHint')})")
        pg.fill("#vpVin", "jtdkb20u093123")
        pg.select_option("#vpBrand", "Toyota")
        pg.fill("#vpModelText", "Corolla")
        pg.click("#vpSave")
        pg.wait_for_timeout(900)
        m = pg.evaluate(f"fetch('/api/vehicles').then(r=>r.json()).then(a=>a.find(x=>x.vin==='{man['vin']}'))")
        ok(m["chassis_number"] == "JTDKB20U093123" and m["vin"] == man["vin"], f"{tag}: the chassis number is saved in upper case without touching the identifier ({m['chassis_number']})")
        ok(m["brand"] == "Toyota" and m["model"] == "Corolla", f"{tag}: brand and free-text model saved ({m['brand']} {m['model']})")
        ok(pg.input_value("#vpBrand") == "Toyota" and pg.input_value("#vpModelText") == "Corolla", f"{tag}: the sheet reloads brand and model")
        pg.fill("#vpVin", "CORTO")
        pg.click("#vpSave")
        pg.wait_for_timeout(600)
        m = pg.evaluate(f"fetch('/api/vehicles').then(r=>r.json()).then(a=>a.find(x=>x.vin==='{man['vin']}'))")
        ok(m["chassis_number"] == "JTDKB20U093123", f"{tag}: a chassis number that is too short is not saved")
        pg.screenshot(path=f"{OUT}/profile-manual-{theme}.png", full_page=True)
        # with another brand there is no official plan: no switch and no official view; the ITV stays
        pg.evaluate("switchTab('maintenance')")
        pg.wait_for_timeout(900)
        ok(pg.is_hidden("#maintModeSwitch") and pg.is_hidden("#maintOfficialView") and pg.is_visible("#maintCustomView"), f"{tag}: another brand only has the custom plan")
        ok(pg.is_visible("#maintItvCard"), f"{tag}: the ITV shows with any brand")
        pg.screenshot(path=f"{OUT}/maintenance-other-brand-{theme}.png", full_page=True)
        pg.evaluate(f"fetch('/api/vehicles/{man['vin']}', {{method: 'DELETE'}}).then(() => loadVehicles()).then(() => selectVehicle('{demo_vin}'))")
        pg.wait_for_timeout(900)
        # Ebro: the official account status only counts the account's cars (not the ones added by hand)
        st = pg.evaluate("fetch('/api/account/status').then(r=>r.json())")
        ok(all(not x["vin"].startswith("MAN") for x in st["vehicles"]), f"{tag}: the Ebro account does not list cars without an account")

        # Sistema: the version
        pg.evaluate("switchTab('settings'); switchSettingsSubTab('system')")
        pg.wait_for_timeout(700)
        ok(txt("#appVersion").startswith("EVBro ") and len(txt("#appVersion")) > 9, f"{tag}: Sistema shows the version ({txt('#appVersion')})")
        ok("Información del Servidor" not in pg.text_content("#settingsSubTabSystem"), f"{tag}: the server info card is gone")
        pg.screenshot(path=f"{OUT}/system-{theme}.png", full_page=True)

        ok(not errs, f"{tag}: no JS errors {errs[:2]}")
        ctx.close()
        if theme == "dark":
            import subprocess
            subprocess.run([os.path.join(os.path.dirname(__file__), "demo_server.sh"), "start"], check=True, capture_output=True)
    b.close()
print("FAILURES:", fails if fails else "none")
sys.exit(1 if fails else 0)
